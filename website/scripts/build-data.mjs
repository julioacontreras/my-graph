// Reads facts the page must not hard-code: the version (root Cargo.toml)
// and the GitHub star count (fetched at build time, refreshed on the client).
import { readFile, writeFile, copyFile } from "node:fs/promises";

const root = new URL("../../", import.meta.url);
const site = new URL("../", import.meta.url);

const cargo = await readFile(new URL("Cargo.toml", root), "utf8");
const block = cargo.split("[workspace.package]")[1] ?? "";
const version = block.match(/^version\s*=\s*"([^"]+)"/m)?.[1];
if (!version) throw new Error("version not found in [workspace.package] of Cargo.toml");

let stars = null;
try {
  const res = await fetch("https://api.github.com/repos/julioacontreras/my-graph", {
    headers: { Accept: "application/vnd.github+json", "User-Agent": "mygraph-website-build" },
    signal: AbortSignal.timeout(5000),
  });
  if (res.ok) stars = (await res.json()).stargazers_count ?? null;
} catch {
  // Offline build: the client fetches the count later.
}

await writeFile(
  new URL("src/data/generated.ts", site),
  `// Generated by scripts/build-data.mjs. Do not edit.\n` +
    `export const VERSION = ${JSON.stringify(version)};\n` +
    `export const MINOR = ${JSON.stringify(version.split(".").slice(0, 2).join("."))};\n` +
    `export const STARS_AT_BUILD: number | null = ${JSON.stringify(stars)};\n`,
);
await copyFile(new URL("docker-compose.yml", root), new URL("public/docker-compose.yml", site));
console.log(`build-data: version ${version}, stars ${stars ?? "unknown"}`);
