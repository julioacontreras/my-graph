// Highlights src/data/snippets/* with Shiki at build time, so Shiki never
// ships to the browser. Output: src/data/snippets.generated.ts
import { readdir, readFile, writeFile } from "node:fs/promises";
import { createHighlighter } from "shiki";

const dir = new URL("../src/data/snippets/", import.meta.url);
const LANG = { py: "python", sh: "bash", yml: "yaml", toml: "toml", rs: "rust", cypher: "cypher" };

const highlighter = await createHighlighter({
  themes: ["github-dark-default"],
  langs: [...new Set(Object.values(LANG))],
});

const out = {};
for (const file of (await readdir(dir)).sort()) {
  const ext = file.split(".").pop();
  const lang = LANG[ext];
  if (!lang) continue;
  const code = (await readFile(new URL(file, dir), "utf8")).replace(/\n$/, "");
  const html = highlighter
    .codeToHtml(code, { lang, theme: "github-dark-default" })
    .replace(/background-color:#[0-9a-fA-F]+;?/, "background-color:transparent;");
  const id = file.replace(/\.[^.]+$/, "");
  out[id] = { code, html, lang };
}

await writeFile(
  new URL("../src/data/snippets.generated.ts", import.meta.url),
  `// Generated by scripts/highlight-snippets.mjs from src/data/snippets/. Do not edit.\n` +
    `export type Snippet = { code: string; html: string; lang: string };\n` +
    `export const snippets = ${JSON.stringify(out, null, 2)} as const satisfies Record<string, Snippet>;\n`,
);
console.log(`highlight-snippets: ${Object.keys(out).length} snippets`);
